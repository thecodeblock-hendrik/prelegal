// Embeds the repo-level Mutual NDA standard terms so templates/ stays the single source of truth.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "../templates/Mutual-NDA.md");
const target = resolve(root, "lib/generated/standardTerms.ts");

mkdirSync(dirname(target), { recursive: true });
const terms = readFileSync(source, "utf8");
writeFileSync(
  target,
  `// Generated by scripts/copy-templates.mjs from templates/Mutual-NDA.md. Do not edit.\nexport const STANDARD_TERMS = ${JSON.stringify(terms)};\n`,
);
